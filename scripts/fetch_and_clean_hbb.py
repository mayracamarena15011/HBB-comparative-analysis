from Bio import Entrez, SeqIO
from Bio.SeqRecord import SeqRecord

# NCBI policy requires an email address
Entrez.email = "mxc3595@mavs.uta.edu"

# The 7 mammalian orthologs and their RefSeq accession IDs
orthologs = [
    {"label": "Human_HBB", "accession": "NP_000509.1", "species": "Homo sapiens"},
    {"label": "Chimpanzee_HBB", "accession": "NP_001139433.1", "species": "Pan troglodytes"},
    {"label": "Macaque_HBB", "accession": "NP_001028096.1", "species": "Macaca mulatta"},
    {"label": "Mouse_HBB", "accession": "NP_001265090.1", "species": "Mus musculus"},
    {"label": "Dog_HBB", "accession": "NP_001003157.1", "species": "Canis lupus familiaris"},
    {"label": "Cattle_HBB", "accession": "NP_776342.1", "species": "Bos taurus"},
    {"label": "Horse_HBB", "accession": "NP_001075253.1", "species": "Equus caballus"}
]

output_filename = "mammalian_HBB_compiled.fasta"
cleaned_records = []

print("=" * 65)
print("FETCHING, CLEANING HEADERS, AND VERIFYING LENGTHS:")
print("=" * 65)

for item in orthologs:
    acc = item["accession"]
    label = item["label"]
    species = item["species"]

    # Download record directly from NCBI Protein
    with Entrez.efetch(db="protein", id=acc, rettype="fasta", retmode="text") as handle:
        record = SeqIO.read(handle, "fasta")
        seq_len = len(record.seq)

        # Check if length falls within expected 146-147 amino acids
        status = "PASS" if 146 <= seq_len <= 147 else "FAIL"
        print(f"[{status}] {label:<16} | Length: {seq_len} aa | {species} ({acc})")

        # Sanitize header to just >Label (eliminates software clipping issues)
        clean_record = SeqRecord(
            seq=record.seq,
            id=label,
            description=""
        )
        cleaned_records.append(clean_record)

# Save the combined records into a single multi-sequence FASTA file
with open(output_filename, "w") as out_file:
    SeqIO.write(cleaned_records, out_file, "fasta")

print("=" * 65)
print(f"Successfully created: {output_filename}")
print("=" * 65)